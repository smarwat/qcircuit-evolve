"""Generate fresh secret test values into hidden_values.json (git-ignored).

    python make_hidden_values.py            # refuses to overwrite an existing file
    python make_hidden_values.py --force

Picks two random hidden widths in 18..30 (never a public width, never a previously
published hidden width), each with a random prime of exactly that bit length, plus a
fresh random 32-bit prime and fresh seeds. Prints nothing secret.
"""

import hashlib
import json
import os
import secrets
import sys

from adversarial import is_prime
from config import HIDDEN_FILE, check_hidden

PUBLIC_WIDTHS = {4, 8, 16, 32}
PUBLIC_PRIMES = {13, 251, 65521, 4294967291}
# Previously published (now burned) hidden widths and primes, stored as truncated SHA-256 of
# "width:<n>" / "prime:<p>" so this file does not republish them. Never reused.
BURNED = {"c3a5bffeeaf92b99", "2be30734b5988168", "57809f44629a368d", "5185e628cde86bbf", "8649587e40be44aa"}


def burned(kind, value):
    return hashlib.sha256(f"{kind}:{value}".encode()).hexdigest()[:16] in BURNED


def random_prime(n):
    while True:
        p = secrets.randbits(n) | (1 << (n - 1)) | 1   # exactly n bits, odd
        if p < (1 << n) and p not in PUBLIC_PRIMES and not burned("prime", p) and is_prime(p):
            return p


def main(argv):
    if os.path.exists(HIDDEN_FILE) and "--force" not in argv:
        print(f"{HIDDEN_FILE} exists; pass --force to replace it", file=sys.stderr)
        return 1
    pool = sorted(n for n in range(18, 31) if n not in PUBLIC_WIDTHS and not burned("width", n))
    widths = []
    while len(widths) < 2:
        n = pool[secrets.randbelow(len(pool))]
        if n not in widths:
            widths.append(n)
    values = {
        "_comment": "SECRET. Never commit. Generated by make_hidden_values.py.",
        "hidden_seed": secrets.randbits(40),
        "verify_seed": secrets.randbits(40),
        "verify_extra_widths": [{"n": n, "p": random_prime(n)} for n in sorted(widths)]
        + [{"n": 32, "p": random_prime(32)}],
    }
    check_hidden(values, "generated values")
    fd = os.open(HIDDEN_FILE, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump(values, f, indent=1)
    print(f"wrote {os.path.basename(HIDDEN_FILE)} (mode 600); values not printed")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
