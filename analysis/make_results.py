"""Generate results/RESULTS.md from the JSON produced by the analysis scripts.

Every number in RESULTS.md is read from results/*.json (or evaluated from the published
formulas in literature.py); the only hand-written inputs are the one-sentence lineage
descriptions in results/lineage_notes.json, which are prose, not numbers.

    .venv-verify/bin/python analysis/make_results.py results/
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from literature import evaluate as literature_at  # noqa: E402


def load(out, name, default=None):
    path = os.path.join(out, name)
    if not os.path.exists(path):
        return default
    with open(path) as f:
        return json.load(f)


def f(x, nd=0):
    if x is None:
        return "–"
    if isinstance(x, float) and nd:
        return f"{x:,.{nd}f}"
    return f"{round(x):,}" if isinstance(x, (int, float)) else str(x)


def poly(c, var="n"):
    terms = []
    for power, coef in zip(range(len(c) - 1, -1, -1), c):
        if abs(coef) < 1e-6:
            continue
        t = f"{coef:.2f}" + (f"{var}^{power}" if power > 1 else (var if power == 1 else ""))
        terms.append(t)
    return " + ".join(terms).replace("+ -", "− ")


def main(argv):
    out = argv[1]
    an = load(out, "analysis.json")
    res = {r["name"]: r for r in load(out, "resources.json")}
    ver = load(out, "verification.json")
    notes = load(out, "lineage_notes.json", {})
    seed, best = res["seed"], res["best"]
    b32 = next(r for r in best["rows"] if r["n"] == 32)
    s32 = next(r for r in seed["rows"] if r["n"] == 32)
    fb = an["final_best"]
    L = []
    w = L.append

    w("# Shor's Edge: results\n")
    w("_Generated by `analysis/make_results.py` from the run logs and analysis JSON. Do not edit by hand._\n")

    # ---- summary ------------------------------------------------------------
    w("## Summary\n")
    w(f"- Final best: **`{fb['id']}`**, T·Q at n=32 = **{f(fb['score'])}** "
      f"(T = {f(fb['T'])} Toffolis, Q = {f(fb['Q'])} qubits).")
    w(f"- Seed (`binary_euclid`, our textbook baseline): T·Q = {f(an['seed_best_tq'])} "
      f"(T = {f(s32['toffolis'])}, Q = {f(s32['qubits'])}). Improvement: **{an['improvement_factor']:.2f}×** "
      f"in T·Q, {s32['toffolis'] / b32['toffolis']:.2f}× in Toffolis, {s32['qubits'] / b32['qubits']:.2f}× in qubits.")
    w(f"- Model calls: {an['calls']} (run `{an['run_dir']}`), all answered by "
      f"{', '.join('`' + m + '`' for m in an['models_answering'])}; model mismatches: {an['model_mismatches']}.")
    w(f"- Calls returning a valid program: {an['valid_rate'] * 100:.0f}%.\n")

    # ---- verification -----------------------------------------------------------
    w("## Verification of the final best\n")
    w("**Project evaluator** (`evaluator.py`): valid at n = 4, 8, 16 (exhaustive) and 32 (edge + public + "
      "hidden random inputs), and passed the hidden verify tier (n = 32 on 20,000 fresh + adversarial "
      "inputs; hidden widths/primes) before it was accepted as best.\n")
    disagreements, incomplete = [], []
    if ver:
        meta = ver["meta"]
        rep = next(r for r in ver["reports"] if r["name"] == "best")
        w(f"**Independent check** (`analysis/independent_verify.py`, Qiskit {meta['qiskit']}, Qiskit Aer "
          f"{meta['qiskit_aer']}, method `{meta['method']}`). It shares no code with `evaluator.py`, "
          "`circuit.py` or `sandbox_runner.py`: its own builder runs the candidate, the gates are exported "
          "to OpenQASM 2 through Qiskit (`results/qasm/`), the QASM file is reloaded, and the reloaded circuit "
          "is simulated.\n")
        w("| n | p | qubits | Toffolis | Toffoli depth | basis inputs checked | failures |")
        w("|---|---|---|---|---|---|---|")
        for r in rep["widths"]:
            w(f"| {r['n']} | {f(r['p'])} | {r['qubits']} | {f(r['toffolis'])} | {f(r['toffoli_depth'])} | "
              f"{f(r['basis']['inputs'])} | **{r['basis']['failures']}** |")
            ev = next((x for x in best["rows"] if x["n"] == r["n"]), None)
            if r["basis"]["failures"]:
                disagreements.append(f"n={r['n']}: {r['basis']['failures']} basis-state failures "
                                     f"(first: {r['basis']['first_failures'][:2]})")
            if ev and (ev["toffolis"], ev["qubits"]) != (r["toffolis"], r["qubits"]):
                disagreements.append(f"n={r['n']}: QASM circuit has T,Q = {r['toffolis']},{r['qubits']} "
                                     f"but the counts from the builder are {ev['toffolis']},{ev['qubits']}")
        if fb["T"] != b32["toffolis"] or fb["Q"] != b32["qubits"]:
            disagreements.append(f"evaluator logged T,Q = {fb['T']},{fb['Q']} at n=32 but the independent "
                                 f"builder counts {b32['toffolis']},{b32['qubits']}")
        w("\nBasis-state inputs: n = 8 all 250 inputs; n = 16 and 32: 200 random inputs plus edge cases and "
          "adversarial inputs (hardest step counts under four GCD-type metrics). n = 4 also runs all inputs.\n")
        st = ver.get("mps_selftest")
        w("**Quantum checks** (n = 4 and 8). The circuit is run on a superposition of inputs. Exact quantities: "
          "the marginal distribution of the input/output qubits, and ⟨ΣZ⟩ over all ancilla qubits, which equals "
          "the number of ancillas exactly when every ancilla is |0⟩ with probability 1 (and then the "
          "input/output state is a product with the ancillas: not entangled). Plus 4,096 measurement shots.\n")
        if st:
            w(f"Simulator self-test before the quantum checks: every Aer MPS primitive used was compared with the "
              f"exact statevector method on a random {st['qubits']}-qubit, {st['gates']}-gate reversible circuit with "
              f"both input preparations: **{'passed' if st['passed'] else 'FAILED'}**.\n")
        w("| n | input preparation | P(input, output) on correct pairs | expected | ⟨ΣZ⟩ over ancillas | ancillas | "
          "inputs with >1 output | shots: wrong output | shots: ancilla ≠ 0 | sim time |")
        w("|---|---|---|---|---|---|---|---|---|---|")
        planned = {4: ["hadamard", "valid"], 8: ["hadamard"]}
        for r in rep["widths"]:
            done = {q["prep"]: q for q in r.get("quantum", [])}
            for prep in planned.get(r["n"], []):
                label = "H on all n input qubits" if prep == "hadamard" else "uniform over valid inputs 1..p−1 (compiled)"
                q = done.get(prep)
                if q is None or "io_mass_on_correct_valid_pairs" not in q:
                    w(f"| {r['n']} | {label} | **NOT COMPLETED** | | | | | | | |")
                    incomplete.append(f"n={r['n']} quantum check ({label})")
                    continue
                w(f"| {r['n']} | {label} | {q['io_mass_on_correct_valid_pairs']:.12f} | {q['expected_mass']:.12f} | "
                  f"{q['ancilla_z_sum']:.9f} | {q['ancillas']} | {q['inputs_with_more_than_one_output']} | "
                  f"{q['shots_on_valid_inputs_with_wrong_output']} | {q['shots_on_valid_inputs_with_nonzero_ancilla']} | "
                  f"{q['sim_seconds']:.0f} s |")
                if abs(q["io_mass_on_correct_valid_pairs"] - q["expected_mass"]) > 1e-9:
                    disagreements.append(f"n={r['n']} {prep}: probability on correct pairs "
                                         f"{q['io_mass_on_correct_valid_pairs']} ≠ {q['expected_mass']}")
                if abs(q["ancilla_z_sum"] - q["ancillas"]) > 1e-6:
                    disagreements.append(f"n={r['n']} {prep}: <ΣZ> over ancillas {q['ancilla_z_sum']} ≠ {q['ancillas']}")
                if q["shots_on_valid_inputs_with_wrong_output"] or q["shots_on_valid_inputs_with_nonzero_ancilla"]:
                    disagreements.append(f"n={r['n']} {prep}: bad shots")
        w("\nReading the table: with Hadamards every input has weight 1/2ⁿ, including the don't-care inputs 0 and "
          "p..2ⁿ−1 whose outputs the task leaves unspecified, so the expected probability on correct (a, a⁻¹ mod p) "
          "pairs is (p−1)/2ⁿ; ⟨ΣZ⟩ covers every branch, don't-cares included. At n = 4 the valid-input "
          "superposition is also run (expected probability 1). At n = 8 only the Hadamard preparation is run; a "
          "second preparation would repeat an hour-long simulation.\n")
        w("**Harness problems found and fixed during verification (disclosed in full).** The first n = 4 quantum "
          "run reported probability 0 on the correct pairs although every basis-state check passed. A reversible "
          "classical circuit is a permutation of basis states, so that combination is impossible for the circuit "
          "itself; the cause was in the harness. (1) With Qiskit Aer 0.18.0's `matrix_product_state` method, "
          "`save_amplitudes` returned zeros after long circuits and `initialize` produced wrong output "
          "distributions; a 14-qubit random reversible circuit compared against the exact statevector method "
          "reproduces both. (2) Our code read `save_probabilities_dict` with hex-string keys while this version "
          "returns integer keys. The verifier now prepares the valid-input state with compiled u/cx gates, avoids "
          "both primitives, reads either key type, and runs the self-test above before any quantum check. The "
          "first run's shots were already consistent with a correct circuit (every valid input gave its inverse, "
          "every ancilla read 0); nothing about the circuit changed.\n")
    else:
        w("_Independent verification has not been run (results/verification.json missing)._\n")
    w("**Disagreements with `evaluator.py`:** " + ("none found." if not disagreements else ""))
    for d in disagreements:
        w(f"- BUG/DISAGREEMENT: {d}")
    if incomplete:
        w("\n**Checks not completed:** " + "; ".join(incomplete) + ".")
    w("")
    rv = load(out, "reverify.json")
    w("**Re-verification with fresh hidden values.** The original hidden seeds, widths and primes were "
      "committed to git earlier, so they were replaced with new secret values (kept in an untracked file) "
      "and the winner was re-checked by the project evaluator.")
    if rv:
        nt, vt = rv["normal_tier"], rv["verify_tier"]
        w(f"Normal tier with new hidden inputs: **{'valid' if nt['valid'] else 'INVALID'}**, T·Q {f(nt['score'])} "
          f"(T = {f(nt['T'])}, Q = {nt['Q']}). Verify tier with a new seed, {vt['hidden_extra_widths']} new hidden "
          f"widths and a new 32-bit prime ({vt['targets']} targets, {f(vt['inputs_checked'])} inputs, "
          f"{f(vt['inputs_at_score_width'])} at n = 32): **{'passed' if vt['passed'] else 'FAILED'}**. "
          "The new widths and primes are not disclosed.\n")
    else:
        w("**NOT RUN** (results/reverify.json missing).\n")

    # ---- resources ------------------------------------------------------------------
    w("## Resources at every width\n")
    w("T-count conventions (as requested): 7 T per Toffoli; and 4 T per Toffoli (Toffolis replaced by "
      "AND gates with measurement-based uncomputation, charged 4 T each, uncomputation included, which "
      "overstates the true cost under Gidney/Häner accounting where AND† costs 0 T). Toffoli depth counts "
      "Toffoli layers, with X and CNOT free but respecting qubit dependencies. Qubits = distinct qubits "
      "touched, including the 2n input/output qubits.\n")
    for name, label in (("seed", "Seed (`binary_euclid`)"), ("best", f"Best (`{fb['id']}`)")):
        r = res[name]
        w(f"**{label}**\n")
        w("| n | p | Toffolis | qubits | Toffoli depth | T-count (7T) | T-count (4T) | T·Q |")
        w("|---|---|---|---|---|---|---|---|")
        for x in r["rows"]:
            if x["task_width"]:
                w(f"| {x['n']} | {f(x['p'])} | {f(x['toffolis'])} | {x['qubits']} | {f(x['toffoli_depth'])} | "
                  f"{f(x['t_count_7'])} | {f(x['t_count_4'])} | {f(x['tq'])} |")
        ft, fq, fd = r["fit_T"], r["fit_Q"], r["fit_Tdepth"]
        w(f"\nFits over every n = 4..32 ({len(r['rows'])} widths; largest prime below 2ⁿ except at the task "
          f"widths): T(n) ≈ {poly(ft['quadratic'])} (max relative error {ft['quadratic_max_rel_err'] * 100:.1f}%), "
          f"log-log slope of T over n = 16..32 = {ft['loglog_slope_n16_32']:.3f}; "
          f"Q(n) ≈ {poly(fq['linear'])} (max relative error {fq['linear_max_rel_err'] * 100:.1f}%); "
          f"Toffoli depth log-log slope {fd['loglog_slope_n16_32']:.3f}. "
          f"**Growth order: T = Θ(n²), Q = Θ(n), Toffoli depth ≈ Θ(n²).**\n")
    w("![log-log T vs n](loglog_T_vs_n.png)\n")

    # ---- literature ----------------------------------------------------------------
    w("## Comparison with published designs (n = 32)\n")
    lit = literature_at(32)
    ours_t7, ours_t4 = b32["t_count_7"], b32["t_count_4"]
    w("| design | qubits (formula → n=32) | cost (formula → n=32) | ours at n=32 | source |")
    w("|---|---|---|---|---|")
    for x in lit:
        ours = (f"{f(b32['toffolis'])} Toffolis, {b32['qubits']} qubits" if x["metric"] == "Toffoli"
                else f"{f(ours_t7)} T (7T) / {f(ours_t4)} T (4T), {b32['qubits']} qubits")
        w(f"| {x['key']} {x['variant']} | {x['qubits_formula']} → {f(x['qubits'], 1)} | "
          f"{x['metric']}: {x['cost_formula']} → {f(x['cost'])} | {ours} | {x['cite']} |")
    w("")
    w("**Accounting differences.**\n")
    seen = set()
    for x in lit:
        for nline in x["notes"]:
            if nline not in seen:
                seen.add(nline)
                w(f"- {nline}")
    w("- Ours: plain inverse a⁻¹ mod p (not Montgomery form), so any 2^k correction is inside our count; input "
      "preserved; output in a fresh register; all ancillas returned to 0 (full uncompute); fixed, "
      "input-independent gate sequence (it is a circuit generated from n and p only); qubits = distinct "
      "qubits touched including the 2n input/output qubits; Toffolis counted exactly from the gate list, "
      "not fitted.")
    w("- Ours is evaluated only at n ≤ 32 (exhaustively for n ≤ 16); the published formulas target "
      "cryptographic sizes (n = 256-521) and were fitted or estimated there.\n")
    w("**Verdict (computed).**\n")
    rnsl = next(x for x in lit if x["key"] == "RNSL2017")
    lowt = next(x for x in lit if x["key"] == "HJNRS2020-LowT")
    loww = next(x for x in lit if x["key"] == "HJNRS2020-LowW")
    dq = b32["qubits"] - rnsl["qubits"]
    w(f"- vs RNSL 2017: our Toffoli count is {rnsl['cost'] / b32['toffolis']:.2f}× lower than their leading-order "
      f"formula, and we use {abs(dq):.0f} {'more' if dq > 0 else 'fewer'} qubits than their {f(rnsl['qubits'])}"
      + (" (they minimised qubits first, so on qubits this is a trade-off)." if dq > 0 else "."))
    for x in (loww, lowt):
        better_q = b32["qubits"] <= x["qubits"]
        w(f"- vs HJNRS 2020 {x['variant']}: their T-count {f(x['cost'])} vs ours {f(ours_t7)} (7 T/Toffoli, "
          f"{x['cost'] / ours_t7:.2f}× lower) or {f(ours_t4)} (4 T/Toffoli, {x['cost'] / ours_t4:.2f}× lower); "
          f"qubits {f(x['qubits'], 1)} vs ours {b32['qubits']} ({'fewer' if better_q else 'more'} for us).")
    # Which published variants does our circuit beat on cost, on qubits, on both? (computed)
    ours_cost = {"Toffoli": b32["toffolis"], "T-count": ours_t7}  # conservative: 7 T per Toffoli
    lower_cost = [x for x in lit if ours_cost[x["metric"]] < x["cost"]]
    fewer_q = [x for x in lit if b32["qubits"] < x["qubits"]]
    both = [x for x in lit if x in lower_cost and x in fewer_q]
    names = lambda xs: ", ".join(f"{x['key']} {x['variant']}" for x in xs) or "none"  # noqa: E731
    # Sanity anchor: how does our *unevolved* textbook seed compare on the same terms?
    seed_lower = [x for x in lit if {"Toffoli": s32["toffolis"], "T-count": s32["t_count_7"]}[x["metric"]] < x["cost"]]
    w(f"- Sanity anchor: our unevolved seed ({f(s32['toffolis'])} Toffolis, {f(s32['t_count_7'])} T at 7 T/Toffoli, "
      f"{s32['qubits']} qubits) already has lower cost than: {names(seed_lower)}. So part of any gap to a published "
      "formula comes from accounting and adder choices (e.g. RNSL's qubit-minimising incrementer adders, which "
      "add the log n factor) rather than from the search.")
    w(f"- Lower cost than (Toffolis vs RNSL; T-count at 7 T/Toffoli vs HJNRS): {names(lower_cost)}.")
    w(f"- Fewer qubits than: {names(fewer_q)}.")
    w(f"- Lower on both axes than: {names(both)}.")
    w("- What this does and does not show: the published values are formulas fitted or estimated by their "
      "authors (RNSL: leading order only, so its true count at n = 32 could be noticeably lower; HJNRS: "
      "regression fits whose constant terms are approximate), for a different output (Montgomery form) and, "
      "for HJNRS, T-counts after Clifford+T compilation with 0-T uncomputation, whereas ours is an uncompiled "
      "Toffoli count. We evaluated their formulas at n = 32 rather than re-implementing their circuits. A "
      "favourable comparison is therefore **not an established improvement over the literature**; the "
      "improvement measured on equal terms is the one over our own textbook baseline (the seed), reported "
      "above. Settling the literature question needs their circuits re-built and counted under our "
      "accounting at n = 32.\n")

    # ---- run analysis ----------------------------------------------------------------
    w("## The run\n")
    w("![best vs call](best_vs_call.png)\n")
    w("![pareto](pareto_T_vs_Q.png)\n")
    w("| call | id | mode | outcome | T | Q | T·Q | best after call | seconds | notional $ | output tokens |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for s in an["series"][1:]:
        usd = "–" if s["notional_usd"] is None else f"{s['notional_usd']:.3f}"
        w(f"| {s['call']} | `{s['id']}` | {s['mode']} | {s['category']} | {f(s['T'])} | {f(s['Q'])} | "
          f"{f(s['score'])} | {f(s['best_tq'])} | {f(s['api_s'])} | {usd} | {f(s['output_tokens'])} |")
    w("")
    w("**Outcomes across all calls**\n")
    w("| category | calls |")
    w("|---|---|")
    for k, v in an["categories"].items():
        w(f"| {k} | {v} |")
    w("")
    w("| mode | calls | valid | new best |")
    w("|---|---|---|---|")
    for k, v in an["by_mode"].items():
        w(f"| {k} | {v['calls']} | {v['valid']} | {v['new_best']} |")
    sp, nu, ot = an["seconds_per_call"], an["notional_usd_per_call"], an["output_tokens_per_call"]
    w(f"\nPer call: median {sp['median']:.0f} s (mean {sp['mean']:.0f}, max {sp['max']:.0f}); notional cost "
      f"median ${nu['median']:.3f}, total ${nu['total']:.2f} (subscription usage, **not billed**); output "
      f"tokens median {f(ot['median'])}, max {f(ot['max'])}. Wall time in model calls: {sp['total'] / 60:.0f} min.\n")

    # ---- lineage -----------------------------------------------------------------------
    w("## Lineage of the winner\n")
    w("One sentence per step, written by hand from the model's explanation (`runs/…/replies/`) and the code diff; "
      "all numbers come from the logs.\n")
    w("| step | id | mode | T | Q | T·Q | change vs parent | idea |")
    w("|---|---|---|---|---|---|---|---|")
    for i, st in enumerate(an["lineage"]):
        d = st["diff_vs_parent"]
        delta = f"+{d['lines_added']}/−{d['lines_removed']} lines" if d else "—"
        w(f"| {i} | `{st['id']}` | {st['mode']} | {f(st['T'])} | {st['Q']} | {f(st['score'])} | {delta} | "
          f"{notes.get(st['id'], '_(no note)_')} |")
    w("")

    # ---- surprises (templated from data) ------------------------------------------------
    w("## Surprises\n")
    # Computed from the data:
    dups = an["categories"].get("duplicate of an archived program", 0)
    if dups:
        w(f"- {dups} of {an['calls']} calls returned a program already in the archive (in redesign mode the model "
          "sometimes resubmitted an inspiration verbatim). The duplicate check caught them before evaluation; a "
          "prompt line forbidding resubmission would recover those calls.")
    rows = [x for x in best["rows"] if x["n"] >= 8]
    mers = [x for x in rows if x["p"] == (1 << x["n"]) - 1]
    other = [x for x in rows if x["p"] != (1 << x["n"]) - 1]
    if mers and other:
        avg = lambda xs: sum(x["toffolis"] / x["n"] ** 2 for x in xs) / len(xs)  # noqa: E731
        w(f"- The winner's cost depends on p, not only on n: over n = 8..32, T/n² averages {avg(mers):.2f} for "
          f"Mersenne primes p = 2ⁿ−1 (n = {', '.join(str(x['n']) for x in mers)}) versus {avg(other):.2f} for the other "
          "primes, because the generator sets its iteration count from bitlen(p·(p−1)) and specialises constants to "
          "p's bits. Together with lower-order effects at small n, this is why a single quadratic in n fits T only "
          f"to within {best['fit_T']['quadratic_max_rel_err'] * 100:.0f}% (the log-log slope over n = 16..32 is "
          f"{best['fit_T']['loglog_slope_n16_32']:.2f}).")
    ql = best["fit_Q"]["linear"]
    w(f"- The winner's qubit count is exactly Q(n) = {ql[0]:.0f}n + {ql[1]:.0f} (fit error "
      f"{best['fit_Q']['linear_max_rel_err'] * 100:.1f}%), the same leading coefficient as RNSL's qubit-minimised "
      "7n + 2⌈log₂ n⌉ + 9, although the search optimised T·Q rather than qubits.")
    # Prose observations (hand-written, no numbers):
    for s in notes.get("_surprises", []):
        w(f"- {s}")
    w("")
    w("## Reproduce\n")
    w("```bash\n.venv/bin/python orchestrator.py --resume runs/smoke2 --generations N --max-calls M   # the run\n"
      ".venv-verify/bin/python analysis/independent_verify.py results/ best=results/best.py\n"
      ".venv-verify/bin/python analysis/resources.py results/ seed=seeds/binary_euclid.py best=results/best.py\n"
      ".venv-verify/bin/python analysis/run_analysis.py runs/smoke2 results/\n"
      ".venv-verify/bin/python analysis/make_results.py results/\n```\n")
    with open(os.path.join(out, "RESULTS.md"), "w") as fh:
        fh.write("\n".join(L))
    print(f"wrote {os.path.join(out, 'RESULTS.md')} ({len(L)} lines); disagreements: {len(disagreements)}")


if __name__ == "__main__":
    main(sys.argv)
